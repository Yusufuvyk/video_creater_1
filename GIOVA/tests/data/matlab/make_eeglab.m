% A small EEGLAB dataset saved as v7 and v7.3 .set files, with EEGLAB's own field set
% (eeg_emptyset), for checking that MNE reads both alike in GIOVA.
out = fileparts(mfilename('fullpath'));

EEG = struct('setname', 'fixture', 'filename', '', 'filepath', '', 'subject', '', 'group', '', ...
             'condition', '', 'session', [], 'comments', '', 'nbchan', 4, 'trials', 1, 'pnts', 1000, ...
             'srate', 250, 'xmin', 0, 'xmax', 999 / 250, 'times', (0:999) / 250 * 1000, ...
             'data', single(reshape(sin((1:4000) / 37) * 20, 4, 1000)), 'icaact', [], 'icawinv', [], ...
             'icasphere', [], 'icaweights', [], 'icachansind', [], 'chanlocs', [], 'urchanlocs', [], ...
             'chaninfo', [], 'ref', 'common', 'event', [], 'urevent', [], 'eventdescription', {{}}, ...
             'epoch', [], 'epochdescription', {{}}, 'reject', [], 'stats', [], 'specdata', [], ...
             'specicaact', [], 'splinefile', '', 'icasplinefile', '', 'dipfit', [], 'history', '', ...
             'saved', 'no', 'etc', []);
EEG.chaninfo = struct('plotrad', [], 'shrink', [], 'nosedir', '+X', 'nodatchans', [], 'icachansind', []);
EEG.chanlocs = struct('labels', {'C3', 'Cz', 'C4', 'Pz'}, 'type', {'EEG', 'EEG', 'EEG', 'EEG'}, ...
                      'X', {[], [], [], []}, 'Y', {[], [], [], []}, 'Z', {[], [], [], []}, ...
                      'theta', {[], [], [], []}, 'radius', {[], [], [], []}, 'urchan', {1, 2, 3, 4});
EEG.event = struct('type', {'S 1', 'S 2', 'S 1'}, 'latency', {101, 501, 801}, 'duration', {0, 0, 0}, ...
                   'urevent', {1, 2, 3});

save(fullfile(out, 'eeglab_v7.set'), '-struct', 'EEG', '-v7');
save(fullfile(out, 'eeglab_v73.set'), '-struct', 'EEG', '-v7.3');
disp('saved eeglab');
